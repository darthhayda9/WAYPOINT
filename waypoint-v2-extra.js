/* WAYPOINT V2.1 — practical trip management and refund watchlist */
(function(){
'use strict';
const one=s=>document.querySelector(s);
const all=s=>Array.from(document.querySelectorAll(s));
const safe=x=>escapeHtml(String(x==null?'':x));
const find=id=>state.trips.find(t=>Number(t.id)===Number(id));
const demo=t=>t&&Number(t.id)<=3;
function ensure(){state.wp2TripNotes=state.wp2TripNotes||{};state.wp2Checklists=state.wp2Checklists||{};state.wp2Refunds=state.wp2Refunds||[];}
function download(name,type,contents){
 const blob=new Blob([contents],{type}),url=URL.createObjectURL(blob),a=document.createElement('a');a.href=url;a.download=name;document.body.appendChild(a);a.click();a.remove();setTimeout(()=>URL.revokeObjectURL(url),1000);
}
function annotateTrips(){
 all('#tripCards .trip-card').forEach(card=>{
  const b=card.querySelector('.open-trip');if(!b)return;
  const t=find(b.dataset.id);if(!t||card.querySelector('.wp21-label'))return;
  const label=document.createElement('small');label.className='wp21-label';
  label.textContent=demo(t)?'SAMPLE TRIP · DOES NOT USE FREE CREDIT':'YOUR TRIP · SAVED IN THIS BROWSER';
  const h=card.querySelector('h3');if(h)h.before(label);
  if(!demo(t))b.textContent='Open & manage trip →';
 });
}
function itineraryText(t){
 const list=state.wp2Checklists[t.id]||{};
 const tasks=['Check passport / visa','Confirm travel booking','Download boarding pass','Pack essentials','Arrange airport transport'];
 const lines=tasks.map((v,i)=>(list[i]?'[x] ':'[ ] ')+v).join('\n');
 return 'WAYPOINT · TRIP ITINERARY\n\n'+t.title+'\nRoute: '+t.route+'\nDates: '+t.dates+'\nFlight / reference: '+t.flight+'\n\nPRE-DEPARTURE CHECKLIST\n'+lines+'\n\nNOTES\n'+(state.wp2TripNotes[t.id]||'')+'\n\nGenerated by Waypoint V2. Trip data is saved locally in this demo. Always verify travel information with your provider.\n';
}
function openTrip(id){
 ensure();const t=find(id);if(!t)return;
 const tasks=['Check passport / entry rules','Confirm booking details','Save boarding pass','Pack essentials','Arrange airport transport'];
 const checked=state.wp2Checklists[id]||{};
 modal(t.title,
  '<div class="wp21-summary"><b>'+safe(t.route)+'</b><small>'+safe(t.dates)+' · '+safe(t.flight)+'</small></div>'+
  '<div class="wp21-modal-bar"><button class="ghost" id="wp21Edit" data-id="'+t.id+'">Edit trip</button><button class="ghost" id="wp21Download" data-id="'+t.id+'">↓ Export</button></div>'+
  '<h4 style="margin:18px 0 9px">Before you go</h4><div class="wp21-checklist">'+tasks.map((v,i)=>'<label><input type="checkbox" class="wp21-task" data-id="'+t.id+'" data-index="'+i+'" '+(checked[i]?'checked':'')+'> <span>'+v+'</span></label>').join('')+'</div>'+
  '<label class="wp21-notes">Trip notes<textarea id="wp21Notes" rows="4" placeholder="Hotel address, train info, plans…">'+safe(state.wp2TripNotes[id]||'')+'</textarea></label>'+
  '<button class="primary full" id="wp21SaveNotes" data-id="'+t.id+'" style="margin-top:14px">Save notes</button>'+
  '<p class="muted-text" style="font-size:11px;margin-top:11px">Changes are saved in this browser only. No airline reservation is changed.</p>');
}
function editTrip(id){
 const t=find(id);if(!t)return;
 modal('Edit trip',
  '<label>Trip name<input id="wp21Title" maxlength="110" value="'+safe(t.title)+'"></label>'+
  '<label>Route<input id="wp21Route" maxlength="70" value="'+safe(t.route)+'"></label>'+
  '<label>Dates<input id="wp21Dates" maxlength="90" value="'+safe(t.dates)+'"></label>'+
  '<label>Flight / booking label<input id="wp21Flight" maxlength="35" value="'+safe(t.flight)+'"></label>'+
  '<button class="primary full" id="wp21SaveEdit" data-id="'+t.id+'">Save changes</button>');
}
function refunds(){
 ensure();const root=one('#wp21Refunds');if(!root)return;
 const rows=state.wp2Refunds;
 const pending=rows.filter(r=>!r.received).reduce((a,r)=>a+r.amount,0);
 const money=pending.toLocaleString('en-AU',{style:'currency',currency:'AUD'});
 root.innerHTML=
  '<div class="wp21-refund-header"><div><div class="wp2-eyebrow">Your money</div><h3>Refund watchlist</h3><p>Track what was promised versus what arrived. No banking or inbox data is connected.</p></div><button class="primary" id="wp21AddRefund">+ Add refund</button></div>'+
  '<div class="wp21-refund-summary"><strong>'+safe(money)+'</strong><small>Additional refunds you are watching · self-reported</small></div>'+
  (rows.length?'<div class="wp21-refund-list">'+rows.map(r=>
   '<div class="wp21-refund-item"><div><b>'+safe(r.title)+'</b><small>'+safe(r.source)+' · '+(r.received?'Marked received':'Waiting for payment')+'</small></div><div><strong>A$'+r.amount.toFixed(2)+'</strong><button class="ghost small-btn wp21-toggle-refund" data-id="'+r.id+'">'+(r.received?'Undo received':'Mark received')+'</button></div></div>').join('')+'</div>':
   '<p class="muted-text">No additional refunds tracked yet. Your sample Qantas paid-seat refund is shown above.</p>')+
  '<div class="wp21-refund-note">Amounts entered here are estimates until matched against your bank statement. Waypoint does not automatically verify refunds in this demo.</div>';
}
function addRefund(){
 modal('Watch a refund',
  '<p class="muted-text">Record an amount you expect back. This does not contact a merchant or your bank.</p>'+
  '<label>Description<input id="wp21RefundTitle" maxlength="100" placeholder="Hotel cancellation refund"></label>'+
  '<label>Merchant / source<input id="wp21RefundSource" maxlength="80" placeholder="Hotel or airline"></label>'+
  '<label>Expected amount (AUD)<input id="wp21RefundAmount" type="number" min="0.01" max="999999" step="0.01" placeholder="85.00"></label>'+
  '<button class="primary full" id="wp21SaveRefund">Add to watchlist</button>');
}
function dataExport(){
 const content=JSON.stringify({format:'waypoint-local-demo-v2',exportedAt:new Date().toISOString(),data:state},null,2);
 download('waypoint-demo-data.json','application/json',content);
 toast('Your local demo data was exported');
}
function setup(){
 ensure();
 const trips=one('#tripsSection');if(trips){
  const notice=document.createElement('div');notice.className='wp21-trip-notice';
  notice.innerHTML='<strong>Start free.</strong> Create three of your own trips with all the demo features. The preloaded example trips do not count. Deleting a created trip does not restore a credit.';
  const cards=one('#tripCards');cards.before(notice);
  annotateTrips();
  if(window.MutationObserver&&cards){new MutationObserver(function(){annotateTrips()}).observe(cards,{childList:true})}
 }
 const money=one('#moneySection');if(money){
  const section=document.createElement('div');section.id='wp21Refunds';section.className='wp21-refund-section';
  money.appendChild(section);refunds();
 }
 const settings=one('#settingsSection .settings-grid');if(settings){
  const el=document.createElement('article');el.className='panel';
  el.innerHTML='<h3>Your demo data</h3><p>Export the trips, expenses and preferences stored in this browser as JSON. No external account is backed up.</p><button class="ghost" id="wp21ExportData">↓ Export local data</button>';
  settings.appendChild(el);
 }
 document.addEventListener('click',e=>{
   const open=e.target.closest('.open-trip');
   if(open&&Number(open.dataset.id)!==1){
     e.preventDefault();e.stopImmediatePropagation();openTrip(Number(open.dataset.id));return;
   }
 },true);
 document.addEventListener('click',e=>{
  const el=e.target;
  if(el.id==='wp21Edit'){editTrip(Number(el.dataset.id));return}
  if(el.id==='wp21Download'){const t=find(el.dataset.id);if(t){download('waypoint-'+t.id+'-itinerary.txt','text/plain',itineraryText(t));toast('Itinerary exported')}return}
  if(el.id==='wp21SaveNotes'){const id=Number(el.dataset.id);state.wp2TripNotes[id]=String(one('#wp21Notes').value||'').slice(0,4000);save();closeModal();toast('Trip notes saved');return}
  if(el.id==='wp21SaveEdit'){
    const t=find(el.dataset.id);if(!t)return;
    const title=one('#wp21Title').value.trim(),route=one('#wp21Route').value.trim();
    if(!title||!route){toast('Enter a trip name and route');return}
    t.title=title.slice(0,110);t.route=route.slice(0,70);t.dates=one('#wp21Dates').value.trim().slice(0,90)||'Dates TBD';
    t.flight=one('#wp21Flight').value.trim().slice(0,35)||'Not assigned';
    save();renderTrips();annotateTrips();closeModal();toast('Trip updated');return;
  }
  if(el.id==='wp21AddRefund'){addRefund();return}
  if(el.id==='wp21SaveRefund'){
    const title=one('#wp21RefundTitle').value.trim(),amount=Number(one('#wp21RefundAmount').value);
    if(!title||!Number.isFinite(amount)||amount<=0||amount>999999){toast('Enter a valid name and refund amount');return}
    state.wp2Refunds.unshift({id:Date.now(),title:title.slice(0,100),source:one('#wp21RefundSource').value.trim().slice(0,80)||'Unknown merchant',amount:Math.round(amount*100)/100,received:false});
    save();refunds();closeModal();toast('Refund added');return;
  }
  const mark=el.closest('.wp21-toggle-refund');
  if(mark){const item=state.wp2Refunds.find(r=>r.id===Number(mark.dataset.id));if(item){item.received=!item.received;save();refunds();toast(item.received?'Refund marked received':'Refund marked pending')}return}
  if(el.id==='wp21ExportData'){dataExport();return}
  if(el.closest('#saveTrip')||el.closest('.delete-trip')||el.id==='resetDemoBtn')setTimeout(function(){ensure();annotateTrips();refunds()},0);
 });
 document.addEventListener('change',e=>{
  const task=e.target.closest('.wp21-task');if(!task)return;
  ensure();const id=task.dataset.id;state.wp2Checklists[id]=state.wp2Checklists[id]||{};
  state.wp2Checklists[id][task.dataset.index]=task.checked;save();
 });
}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',setup);else setup();
})();
